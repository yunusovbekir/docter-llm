import console from 'node:console'
import { readFile, writeFile } from 'node:fs/promises'
import { URL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const liveSchema = 'http://127.0.0.1:8000/openapi.json'
const fallbackSchema = new URL('../src/api/openapi.json', import.meta.url)
const output = new URL('../src/api/schema.d.ts', import.meta.url)

async function loadSchema() {
  let reason
  try {
    const response = await globalThis.fetch(liveSchema, {
      signal: globalThis.AbortSignal.timeout(5000),
    })
    if (response.ok) return response.json()
    reason = `HTTP ${response.status}`
  } catch (error) {
    reason = error.message
  }

  const fallback = await readFile(fallbackSchema, 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error
    throw new Error(`Could not load ${liveSchema} (${reason}); src/api/openapi.json is missing.`)
  })

  console.warn(`Could not load ${liveSchema} (${reason}); using src/api/openapi.json.`)
  return JSON.parse(fallback)
}

const declarations = astToString(await openapiTS(await loadSchema()))
await writeFile(output, `// Generated by pnpm gen:api. Do not edit.\n\n${declarations}`, 'utf8')
